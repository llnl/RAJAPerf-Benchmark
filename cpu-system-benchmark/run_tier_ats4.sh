#!/usr/bin/env bash
set -euo pipefail

readonly SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
readonly KIB=1024
readonly MIB=$((1024 * KIB))

readonly SOCKETS_PER_NODE=4
readonly CHIPLETS_PER_SOCKET=3
readonly CORES_PER_CHIPLET=8
readonly RESERVED_CORES_PER_CHIPLET=1
readonly RANKS_PER_CHIPLET=$((CORES_PER_CHIPLET - RESERVED_CORES_PER_CHIPLET))
readonly RANKS_PER_NODE=$((
  RANKS_PER_CHIPLET * CHIPLETS_PER_SOCKET * SOCKETS_PER_NODE
))

readonly L2_BYTES_PER_CORE=$((1 * MIB))
readonly L3_BYTES_PER_CHIPLET=$((32 * MIB))
readonly L4_BYTES_PER_SOCKET=$((256 * MIB))
readonly TOTAL_CACHE_BYTES=$((
  RANKS_PER_NODE * L2_BYTES_PER_CORE +
    SOCKETS_PER_NODE *
      (CHIPLETS_PER_SOCKET * L3_BYTES_PER_CHIPLET + L4_BYTES_PER_SOCKET)
))
readonly CACHE_BYTES_PER_CORE=$((TOTAL_CACHE_BYTES / RANKS_PER_NODE))

export CPU_BENCH_SYSTEM="ATS4_MI300A_Zen4"
export CPU_BENCH_SCHEDULER="flux"
export CPU_BENCH_RANKS="$RANKS_PER_NODE"
export CPU_BENCH_CACHE_BYTES_PER_CORE="$CACHE_BYTES_PER_CORE"

exec "${SCRIPT_DIR}/run_tier_cpu.sh" "$@"
